import type {AlarmEvent,Sample,User} from '../packages/contracts/model';
const directory=()=>fs.mkdtempSync(path.join(os.tmpdir(),'scada-p0-'));
const alarmEvent=(id:string,patch:Partial<AlarmEvent>):AlarmEvent=>({id,ruleId:'r',name:'n',severity:'warning',kind:'high',tagId:'tag-m0',tagCode:'M0',value:1,limit:1,message:'m',raisedAt:Date.now(),clearedAt:null,ackAt:null,ackBy:'',popup:false,...patch});
test('outstanding alarms are never truncated and severity outranks recency',()=>{
 const db=new Store(directory());
 const criticalId=randomUUID();
 db.saveAlarm(alarmEvent(criticalId,{severity:'critical',raisedAt:Date.now()-10_000_000}));
 for(let i=0;i<259;i++)db.saveAlarm(alarmEvent(randomUUID(),{severity:'warning',raisedAt:Date.now()-i}));
 const alarms=new Alarms(db,{},()=>[],()=>null);
 assert.equal(alarms.outstanding().length,260,'outstanding() must expose the full unacknowledged set, not a windowed slice');
 const pending=alarms.pending(200);
 assert.equal(pending.length,200,'pending() truncates for transport');
 assert.equal(pending[0].id,criticalId,'critical severity sorts first even though it is by far the oldest event');
 const counts=alarms.counts();
 assert.equal(counts.outstanding,260,'counts() reports the true total, unaffected by pending() truncation');
 assert.equal(counts.unackedOutstanding,260);
 assert.equal(counts.critical,1);
 assert.equal(counts.active,260);
 assert.equal(counts.unacked,260);
 assert.equal(alarms.acknowledge([criticalId],'operator'),1);
 assert.equal(db.unackedAlarms().length,259,'store.unackedAlarms must drop acknowledged events');
 assert.ok(!db.unackedAlarms().some(e=>e.id===criticalId));
 assert.equal(alarms.counts().unackedOutstanding,259);
 db.close();
});
test('store.alarmCounts totals active, unacked and both combined',()=>{
 const db=new Store(directory());
 db.saveAlarm(alarmEvent('a1',{}));
 db.saveAlarm(alarmEvent('a2',{clearedAt:Date.now()}));
 db.saveAlarm(alarmEvent('a3',{ackAt:Date.now(),ackBy:'op'}));
 db.saveAlarm(alarmEvent('a4',{clearedAt:Date.now(),ackAt:Date.now(),ackBy:'op'}));
 assert.deepEqual(db.alarmCounts(),{total:4,active:2,unacked:2,activeUnacked:1});
 db.close();
});
test('settled recognizes terminal status and executions dropped from pending, regardless of tracking',()=>{
 const db=new Store(directory()),samples:Record<string,Sample>={};
 const svc=new Commands(db,samples,()=>db.config(),()=>true,async()=>{});
 const base={commandId:'cmd-pair-0',name:'x',user:'u',value:true as const,createdAt:0,updatedAt:0,message:'',steps:[],configRevision:1,screenId:'s',screenVersion:1};
 const terminalButTracked={...base,id:'e1',status:'uncertain'};svc.pending.set('e1',terminalButTracked);
 assert.equal(svc.settled(terminalButTracked),true,'a terminal status is settled even while still in pending');
 const activeAndTracked={...base,id:'e2',status:'sent'};svc.pending.set('e2',activeAndTracked);
 assert.equal(svc.settled(activeAndTracked),false,'a non-terminal status tracked in pending is not settled');
 const activeButDropped={...base,id:'e3',status:'sent'};
 assert.equal(svc.settled(activeButDropped),true,'dropped from pending counts as settled even with a non-terminal status');
 db.close();
});
test('a late write reply cannot revert a timed-out command and locks the target until a fresh sample arrives',async()=>{
 const dir=directory(),db=new Store(dir),samples:Record<string,Sample>={};
 const c=structuredClone(db.config());
 c.commands.find(d=>d.id==='cmd-pair-0')!.timeoutMs=20;
 c.tags.forEach(t=>samples[t.id]={value:false,quality:'good',receivedAt:Date.now(),sampledAt:Date.now(),sequence:1});
 let started:()=>void;const writeStarted=new Promise<void>(r=>{started=r});
 const svc=new Commands(db,samples,()=>c,()=>true,async()=>{started();await new Promise(r=>setTimeout(r,80));});
 const s=db.screens()[0],id=randomUUID(),user:User={id:'u',username:'u',role:'operator'};
 svc.request({id,commandId:'cmd-pair-0',value:true,screenId:s.id,screenVersion:1},user,s);
 await writeStarted;await new Promise(r=>setTimeout(r,30));
 svc.tick();
 assert.equal(db.command(id)?.status,'uncertain','timing out while the write is in flight settles the command as uncertain');
 await new Promise(r=>setTimeout(r,100));
 assert.equal(db.command(id)?.status,'uncertain','the late write reply must not flip the terminal status back to acknowledged');
 assert.ok(db.events().some(e=>e.action==='command.late'&&(e.details as any).id===id),'the late arrival is audited as command.late');
 assert.throws(()=>svc.request({id:randomUUID(),commandId:'cmd-tag-m0',value:true,screenId:s.id,screenVersion:1},user,s),/sonucu belirsiz/,'a new command on the unsettled target is rejected');
 samples['tag-m0']={value:true,quality:'good',receivedAt:Date.now(),sampledAt:Date.now(),sequence:2};
 assert.doesNotThrow(()=>svc.request({id:randomUUID(),commandId:'cmd-tag-m0',value:true,screenId:s.id,screenVersion:1},user,s),'a fresh good sample clears the lock and the next command is accepted');
 await new Promise(r=>setTimeout(r,100));
 db.close();
});
test('users table migrates in a disabled column that defaults to enabled',()=>{
 const dir=directory();
 const raw=new DatabaseSync(path.join(dir,'scada.sqlite'));
 raw.exec('CREATE TABLE users (id TEXT PRIMARY KEY, username TEXT UNIQUE NOT NULL, role TEXT NOT NULL, hash TEXT NOT NULL);');
 raw.prepare('INSERT INTO users VALUES (?,?,?,?)').run('u1','legacy','operator','hash');
 raw.close();
 const db=new Store(dir);
 db.db.prepare('INSERT INTO users (id,username,role,hash,disabled) VALUES (?,?,?,?,0)').run('u2','fresh','viewer','hash2');
 const rows=(db.db.prepare('SELECT username,disabled FROM users ORDER BY username').all() as any[]).map(r=>({username:r.username,disabled:r.disabled}));
 assert.deepEqual(rows,[{username:'fresh',disabled:0},{username:'legacy',disabled:0}],'a pre-existing install without the column is migrated and defaults to 0');
 db.close();
});
